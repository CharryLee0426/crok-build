export const DICTIONARIES: Record<Lang, Dict> = { en, "zh-Hans": zhHans, ja, es, fr, de };

/** The best of our languages for a list of BCP 47 tags (navigator.languages or Accept-Language), English otherwise. */
export function pickLang(tags: readonly string[]): Lang {
  for (const raw of tags) {
    const tag = raw.trim().toLowerCase();
    if (!tag) continue;
    if (tag === "zh" || tag.startsWith("zh-") || tag.startsWith("zh_")) return "zh-Hans";
    const base = tag.split(/[-_]/)[0];
    if (base === "en" || base === "ja" || base === "es" || base === "fr" || base === "de") return base;
  }
  return "en";
}

/** Parses an Accept-Language header into tags, best first. */
export function parseAcceptLanguage(header: string | null | undefined): string[] {
  if (!header) return [];
  return header
    .split(",")
    .map((part) => {
      const [tag, ...params] = part.trim().split(";");
      const q = params.map((p) => p.trim()).find((p) => p.startsWith("q="));
      return { tag: tag.trim(), q: q ? Number(q.slice(2)) || 0 : 1 };
    })
    .filter((entry) => entry.tag && entry.tag !== "*")
    .sort((a, b) => b.q - a.q)
    .map((entry) => entry.tag);
}

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

export type Vars = Record<string, string | number>;

export function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  return interpolate(DICTIONARIES[lang][key] ?? en[key], vars);
}

/** `_one` for counts the language treats as singular (1 in English, 0 and 1 in French), `_other` for the rest. */
export function pluralKey(lang: Lang, base: PluralBase, count: number): MessageKey {
  const category = new Intl.PluralRules(lang).select(count);
  return (category === "one" ? `${base}_one` : `${base}_other`) as MessageKey;
}

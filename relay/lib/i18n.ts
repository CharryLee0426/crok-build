/** Keys that come in `_one` / `_other` pairs, by their base name. */
export type PluralBase = {
  [K in MessageKey]: K extends `${infer Base}_one` ? (`${Base}_other` extends MessageKey ? Base : never) : never;
}[MessageKey];


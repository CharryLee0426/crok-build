function n(value: number): string {
  return String(Math.round(value * 100) / 100);
}

/** A circle as path data. */
function c(cx: number, cy: number, r: number): string {
  return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(2 * r)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-2 * r)} 0`;
}

/** A rounded rectangle as path data. */
function rr(x: number, y: number, w: number, h: number, r: number): string {
  return (
    `M${n(x + r)} ${n(y)}h${n(w - 2 * r)}a${n(r)} ${n(r)} 0 0 1 ${n(r)} ${n(r)}v${n(h - 2 * r)}` +
    `a${n(r)} ${n(r)} 0 0 1 ${n(-r)} ${n(r)}h${n(-(w - 2 * r))}a${n(r)} ${n(r)} 0 0 1 ${n(-r)} ${n(-r)}` +
    `v${n(-(h - 2 * r))}a${n(r)} ${n(r)} 0 0 1 ${n(r)} ${n(-r)}z`
  );
}

/** A regular polygon, or a star when `inner` differs (`points` outer corners). */
function poly(points: number, outer: number, inner = outer, cx = 12, cy = 12): string {
  const corners = inner === outer ? points : points * 2;
  const parts: string[] = [];
  for (let i = 0; i < corners; i++) {
    const r = inner === outer || i % 2 === 0 ? outer : inner;
    const angle = -Math.PI / 2 + (i * 2 * Math.PI) / corners;
    parts.push(`${i ? "L" : "M"}${n(cx + r * Math.cos(angle))} ${n(cy + r * Math.sin(angle))}`);
  }
  return `${parts.join("")}z`;
}


/**
 * Names that come from the data (series and row names: models, providers, "Cache read", "input · openrouter"): each
 * " · " part translated when the table knows it, left as it is otherwise. Not recorded: models are no words.
 */
export function nameTranslator(lang: Lang): (name: string) => string {
  if (lang === "en") return (name) => name;
  return (name) =>
    name
      .split(" · ")
      .map((part) => STRINGS[part]?.[lang] ?? part)
      .join(" · ");
}

/** Set by relay/scripts/o11y-preview.mjs --strings to list every word the pages ask for. */
type Recorder = { o11yStrings?: Set<string> };

export function translator(lang: Lang): (english: string) => string {
  const record = (globalThis as Recorder).o11yStrings;
  if (lang === "en") return (english) => (record?.add(english), english);
  return (english) => (record?.add(english), STRINGS[english]?.[lang] ?? english);
}

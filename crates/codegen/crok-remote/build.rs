//! Builds a relay into crok, so nobody types its address.
//!
//! `CROK_RELAY_ENV` picks one of `relay/environments/<name>.env`: `prod` unless a test build says `dev` (the
//! Makefile's `build-test-*` targets do). `CROK_REMOTE_DEFAULT_URL` builds in a relay of one's own instead. Every
//! environment's address is built in too, so a prod build can tell a dev sign-in from its own (`credentials.rs`).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const ENV_VAR: &str = "CROK_RELAY_ENV";
const URL_VAR: &str = "CROK_REMOTE_DEFAULT_URL";
const DEFAULT_ENV: &str = "prod";

fn main() {
    println!("cargo:rerun-if-env-changed={ENV_VAR}");
    println!("cargo:rerun-if-env-changed={URL_VAR}");
    println!("cargo:rerun-if-changed=build.rs");
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let dir = manifest.join("../../../relay/environments");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut environments = Vec::new();
    for entry in std::fs::read_dir(&dir)
        .unwrap_or_else(|err| panic!("{} cannot be read: {err}", dir.display()))
    {
        let path = entry.expect("read relay/environments").path();
        let Some(name) = path
            .file_name()
            .and_then(|name| name.to_str())
            .and_then(|name| name.strip_suffix(".env"))
        else {
            continue;
        };
        println!("cargo:rerun-if-changed={}", path.display());
        environments.push((name.to_owned(), convex_url(&path)));
    }
    environments.sort();

    let chosen = std::env::var(ENV_VAR)
        .ok()
        .map(|value| value.trim().to_owned())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| DEFAULT_ENV.to_owned());
    let custom = std::env::var(URL_VAR)
        .ok()
        .map(|value| value.trim().trim_end_matches('/').to_owned())
        .filter(|value| !value.is_empty());
    let (env, url) = match custom {
        // A relay of one's own, unless it is one of the environments after all.
        Some(url) => match environments.iter().find(|(_, known)| *known == url) {
            Some((name, _)) => (name.clone(), url),
            None => ("custom".to_owned(), url),
        },
        None => {
            let url = environments
                .iter()
                .find(|(name, _)| *name == chosen)
                .map(|(_, url)| url.clone())
                .unwrap_or_else(|| {
                    let names: Vec<&str> = environments.iter().map(|(name, _)| name.as_str()).collect();
                    panic!("{ENV_VAR}={chosen} names no relay; use one of {names:?} (relay/environments)")
                });
            (chosen, url)
        }
    };

    let mut out = String::from("// Generated by build.rs from relay/environments and CROK_RELAY_ENV.\n");
    let _ = writeln!(out, "/// The environment this build signs in to: `prod`, `dev`, or `custom`.");
    let _ = writeln!(out, "pub const BUILT_IN_ENV: &str = {env:?};");
    let _ = writeln!(out, "/// The relay this build signs in to.");
    let _ = writeln!(out, "pub const BUILT_IN_URL: &str = {url:?};");
    let _ = writeln!(out, "/// Every environment's relay, by name.");
    let _ = writeln!(out, "pub const ENVIRONMENTS: &[(&str, &str)] = &{environments:?};");
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("relay_environment.rs"), out).expect("write relay_environment.rs");
}

/// The file's `CONVEX_URL`, without a trailing slash.
fn convex_url(path: &Path) -> String {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|err| panic!("{} cannot be read: {err}", path.display()));
    let url = text
        .lines()
        .map(str::trim)
        .filter(|line| !line.starts_with('#'))
        .find_map(|line| line.strip_prefix("CONVEX_URL="))
        .map(|value| value.trim().trim_end_matches('/').to_owned())
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| panic!("{} sets no CONVEX_URL", path.display()));
    assert!(
        url.starts_with("https://") || url.starts_with("http://"),
        "{}: CONVEX_URL must be an http(s) address, not {url:?}",
        path.display()
    );
    url
}

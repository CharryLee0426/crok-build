pub(crate) fn lookup(locale: Locale, key: &str) -> Option<&'static str> {
    let idx = MESSAGES
        .binary_search_by_key(&key, |e| e.key)
        .ok()?;
    let entry = &MESSAGES[idx];
    Some(match locale {
        Locale::En => entry.en,
        Locale::ZhHans => entry.zh,
        Locale::Ja => entry.ja,
        Locale::Es => entry.es,
        Locale::Fr => entry.fr,
        Locale::De => entry.de,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn messages_sorted() {
        for w in MESSAGES.windows(2) {
            assert!(
                w[0].key < w[1].key,
                "catalog not sorted: {:?} >= {:?}",
                w[0].key,
                w[1].key
            );
        }
    }

    fn texts(e: &Entry) -> [(&'static str, &'static str); 6] {
        [
            ("en", e.en),
            ("zh", e.zh),
            ("ja", e.ja),
            ("es", e.es),
            ("fr", e.fr),
            ("de", e.de),
        ]
    }

    /// `{name}` placeholders in `text`, sorted.
    fn placeholders(text: &str) -> Vec<&str> {
        let mut found = Vec::new();
        let mut rest = text;
        while let Some(open) = rest.find('{') {
            let Some(len) = rest[open..].find('}') else {
                break;
            };
            let name = &rest[open + 1..open + len];
            if !name.is_empty() && name.bytes().all(|b| b.is_ascii_lowercase() || b == b'_') {
                found.push(name);
            }
            rest = &rest[open + len + 1..];
        }
        found.sort_unstable();
        found
    }

    #[test]
    fn every_language_has_every_message() {
        for e in MESSAGES {
            for (lang, text) in texts(e) {
                assert!(!text.trim().is_empty(), "{} has no {lang} text", e.key);
            }
        }
    }

    /// A translation that drops or renames a placeholder shows the raw `{name}` or loses the value.
    #[test]
    fn translations_keep_the_placeholders() {
        for e in MESSAGES {
            let expected = placeholders(e.en);
            for (lang, text) in texts(e) {
                assert_eq!(
                    placeholders(text),
                    expected,
                    "{} ({lang}) placeholders differ from English",
                    e.key
                );
                assert_eq!(
                    text.matches('\n').count(),
                    e.en.matches('\n').count(),
                    "{} ({lang}) line breaks differ from English",
                    e.key
                );
            }
        }
    }

    /// The footer hints are `<keys> <action>`: the keys are the same in every language.
    #[test]
    fn hints_keep_their_key_names() {
        const PHRASES: &[&str] = &[
            "settings.hint.double_click_select",
            "settings.hint.type_to_edit",
            "settings.hint.type_to_filter",
        ];
        for e in MESSAGES {
            if !e.key.starts_with("settings.hint.") || PHRASES.contains(&e.key) {
                continue;
            }
            let keys = e.en.split(' ').next().unwrap_or_default();
            for (lang, text) in texts(e) {
                assert_eq!(
                    text.split(' ').next().unwrap_or_default(),
                    keys,
                    "{} ({lang}) must start with the key names",
                    e.key
                );
            }
        }
    }
}

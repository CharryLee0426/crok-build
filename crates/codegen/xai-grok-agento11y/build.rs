//! Builds a destination into crok, so every install reports to the same Agent Observability stack
//! with nothing to set up.
//!
//! `CROK_AGENTO11Y_BUILTIN_ENV` names a settings file in the `agento11y.env` format (the Makefile
//! passes `~/.crok/agento11y.env` when it exists, and `release/publish.sh` requires it). Its
//! `AGENTO11Y_*` and `OTEL_*` lines are kept, masked so the token is not plain text in the binary;
//! the file itself never enters the repository. Without the variable crok has no built-in
//! destination and reports only where `agento11y.env` or the environment says.

use std::fmt::Write as _;
use std::path::PathBuf;

const VAR: &str = "CROK_AGENTO11Y_BUILTIN_ENV";
/// XOR mask for the kept lines; `src/builtin.rs` reads it from the generated file.
const MASK: &[u8] = b"crok/agento11y builtin destination";
/// Lines that only make sense on the machine that built crok.
const LOCAL_ONLY: [&str; 2] = ["AGENTO11Y_DEBUG", "AGENTO11Y_ENABLED"];

fn main() {
    println!("cargo:rerun-if-env-changed={VAR}");
    println!("cargo:rerun-if-changed=build.rs");
    let source = std::env::var(VAR)
        .ok()
        .filter(|path| !path.trim().is_empty())
        .map(|path| PathBuf::from(path.trim()));
    let kept = match &source {
        Some(path) => {
            println!("cargo:rerun-if-changed={}", path.display());
            let text = std::fs::read_to_string(path).unwrap_or_else(|err| {
                panic!(
                    "{VAR} names {}, which cannot be read: {err}",
                    path.display()
                )
            });
            let kept = destination_lines(&text);
            assert!(
                kept.iter().any(|line| line
                    .split_once('=')
                    .is_some_and(|(key, value)| key.trim() == "AGENTO11Y_ENDPOINT"
                        && !value.trim().is_empty())),
                "{VAR} names {}, which sets no AGENTO11Y_ENDPOINT",
                path.display()
            );
            kept
        }
        None => Vec::new(),
    };
    let masked: Vec<u8> = kept
        .join("\n")
        .bytes()
        .zip(MASK.iter().cycle())
        .map(|(byte, mask)| byte ^ mask)
        .collect();
    let mut out = String::from("// Generated by build.rs from CROK_AGENTO11Y_BUILTIN_ENV.\n");
    let _ = writeln!(out, "const BUILTIN_MASK: &[u8] = &{MASK:?};");
    let _ = writeln!(out, "const BUILTIN_MASKED: &[u8] = &{masked:?};");
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("builtin_destination.rs"), out)
        .expect("write builtin_destination.rs");
}

/// The file's `AGENTO11Y_*` / `OTEL_*` assignments, comments and `export` dropped, values as written
/// (the runtime parser in `settings.rs` undoes quoting).
fn destination_lines(text: &str) -> Vec<String> {
    text.lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| line.strip_prefix("export ").unwrap_or(line))
        .filter(|line| {
            line.split_once('=').is_some_and(|(key, _)| {
                let key = key.trim();
                (key.starts_with("AGENTO11Y_") || key.starts_with("OTEL_"))
                    && !LOCAL_ONLY.contains(&key)
            })
        })
        .map(str::to_owned)
        .collect()
}

// Bundles the bridge and its npm dependencies into one ES module, dist/agento11y-bridge.mjs.
// crok embeds that file (include_str!), so building crok needs no Node; only changing the
// bridge does. Commit the rebuilt file with the source change.
//
//   node build.mjs           rebuild dist/agento11y-bridge.mjs
//   node build.mjs --check   fail when the committed bundle is not what the source builds to
//   node build.mjs --tests   bundle test/*.test.ts into .test-dist/ for `node --test`

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const bundlePath = join(here, "dist", "agento11y-bridge.mjs");

// The SDK loads its gRPC exporter with a dynamic import, but bundling hoists that module's
// `@grpc/grpc-js` import to the top of the file, where it fails to resolve. crok sends
// generations over HTTP (AGENTO11Y_PROTOCOL=http), so the gRPC packages are not installed
// and the exporter is replaced by one that says so.
const grpcExporterStub = {
  name: "agento11y-grpc-stub",
  setup(build) {
    // `exporters/default.js` loads it as `import('./grpc.js')`.
    build.onResolve({ filter: /^\.\/grpc\.js$/ }, (args) =>
      /@grafana[\\/]agento11y-core[\\/]dist[\\/]exporters[\\/]/.test(args.importer)
        ? { path: "grpc.js", namespace: "grpc-stub" }
        : undefined,
    );
    build.onLoad({ filter: /.*/, namespace: "grpc-stub" }, () => ({
      contents:
        "export class GRPCGenerationExporter { constructor() { throw new Error(" +
        "\"crok's agento11y bridge exports generations over HTTP only: set AGENTO11Y_PROTOCOL=http\"); } }",
      loader: "js",
    }));
  },
};

// Some OpenTelemetry packages are CommonJS and call require() for Node built-ins,
// which an ES module bundle only has when it makes one.
const requireShim = 'import { createRequire as __crokCreateRequire } from "node:module";\n' +
  "const require = __crokCreateRequire(import.meta.url);";

const shared = {
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  plugins: [grpcExporterStub],
  banner: { js: requireShim },
  legalComments: "eof",
  logLevel: "warning",
};

const mode = process.argv[2];

if (mode === "--tests") {
  const tests = readdirSync(join(here, "test"))
    .filter((name) => name.endsWith(".test.ts"))
    .map((name) => join(here, "test", name));
  await build({ ...shared, entryPoints: tests, outdir: join(here, ".test-dist"), outExtension: { ".js": ".mjs" } });
} else {
  const result = await build({
    ...shared,
    entryPoints: [join(here, "src", "main.ts")],
    write: false,
    outfile: bundlePath,
    banner: { js: `// Generated by build.mjs from src/ and the locked npm packages. Do not edit.\n${requireShim}` },
  });
  const text = result.outputFiles[0].text;
  if (mode === "--check") {
    const committed = readFileSync(bundlePath, "utf8");
    if (committed !== text) {
      console.error("dist/agento11y-bridge.mjs is out of date: run `npm run build` in this directory and commit it.");
      process.exit(1);
    }
  } else {
    mkdirSync(dirname(bundlePath), { recursive: true });
    writeFileSync(bundlePath, text);
    console.log(`wrote ${bundlePath} (${Math.round(text.length / 1024)} KiB)`);
  }
}
